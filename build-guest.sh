#!/usr/bin/env bash
set -euo pipefail
infra=$(cd "$(dirname "$0")" && pwd)
cd "${1:?Usage: build-guest.sh APPLICATION_DIRECTORY}"
mkdir -p build src/generated
generated_stage=$(mktemp -d "$PWD/src/generated/.guests-XXXXXX")
Cleanup() {
    for name in connection_guest_bytes.h business_guest_bytes.h broker_guest_bytes.h; do
        if [[ -f "$generated_stage/$name" ]]; then unlink "$generated_stage/$name"; fi
    done
    rmdir "$generated_stage"
}
trap Cleanup EXIT
sysroot=${WASI_SYSROOT:-"$infra/build/wasi-toolchain/usr"}
builtins=${WASI_BUILTINS:-"$sysroot/lib/llvm-18/lib/clang/18/lib/wasi/libclang_rt.builtins-wasm32.a"}
if [[ ! -f "$sysroot/lib/wasm32-wasi/libc.a" || ! -f "$builtins" ]]; then
    echo 'Set WASI_SYSROOT and WASI_BUILTINS to the WASI C sysroot and compiler-rt archive (see tests/wasm-memory.sh).' >&2
    exit 1
fi
"${WASI_CC:-clang}" --target=wasm32-wasi --sysroot="$sysroot" -std=c11 -O2 \
    -Wall -Wextra -Wpedantic -Werror=enum-compare -Werror=enum-conversion -Werror -nostdlib -I"$infra/external/common" -I"$infra/external/secure-backends" -I"$infra/src" -Isrc/generated \
    "$infra/src/guest/connection.c" src/generated/app-routes.c "$infra/src/http_response.c" "$infra/external/secure-backends/http.c" "$infra/external/secure-backends/http_response_message.c" \
    "$infra/external/common/bump.c" "$infra/external/common/wasm_memory.c" \
    "$sysroot/lib/wasm32-wasi/libc.a" "$builtins" \
    -Wl,--no-entry,--export=ConnectionInit,--export=ConnectionStep,--export-memory \
    -Wl,--initial-memory=131072,--max-memory=2097152 -o build/connection-guest.wasm
# Generated C data only; native host links no HTTP parsing implementation.
{
    printf '/* Generated by build-guest.sh from connection-guest.wasm. */\n#include "types.h"\n\n'
    xxd -i -n connection_guest_bytes build/connection-guest.wasm | \
        sed 's/^unsigned char/static const u8/; s/^unsigned int/static const usize/'
} > "$generated_stage/connection_guest_bytes.h"
"${WASI_CC:-clang}" --target=wasm32-wasi --sysroot="$sysroot" -std=c11 -O2 \
    -Wall -Wextra -Wpedantic -Werror -nostdlib -I"$infra/external/common" -I"$infra/external/secure-backends" -Isrc/generated \
    "$infra/src/guest/business.c" src/generated/app-business.c src/generated/app-queries.c src/business/*.c "$infra/external/secure-backends/query.c" "$infra/external/secure-backends/business_handler.c" "$infra/external/secure-backends/http_response_builder.c" "$infra/external/secure-backends/http_response_message.c" \
    "$infra/external/common/bump.c" "$infra/external/common/wasm_memory.c" \
    "$sysroot/lib/wasm32-wasi/libc.a" "$builtins" \
    -Wl,--no-entry,--export=BusinessInit,--export=BusinessHandle,--export=BusinessContinue,--export=__stack_pointer,--export-table,--export-memory \
    -Wl,--initial-memory=131072,--max-memory=2097152 -o build/business-guest.wasm
{
    printf '/* Generated by build-guest.sh from business-guest.wasm. */\n#include "types.h"\n\n'
    xxd -i -n business_guest_bytes build/business-guest.wasm | \
        sed 's/^unsigned char/static const u8/; s/^unsigned int/static const usize/'
} > "$generated_stage/business_guest_bytes.h"
"${WASI_CC:-clang}" --target=wasm32-wasi --sysroot="$sysroot" -std=c11 -O2 \
    -Wall -Wextra -Wpedantic -Werror -nostdlib -I"$infra/external/common" -I"$infra/external/secure-backends" -Isrc/generated \
    "$infra/src/guest/broker.c" src/generated/app-broker.c src/generated/app-queries.c "$infra/external/secure-backends/query.c" \
    "$infra/external/common/bump.c" "$infra/external/common/wasm_memory.c" \
    "$sysroot/lib/wasm32-wasi/libc.a" "$builtins" \
    -Wl,--no-entry,--export=BrokerInit,--export=BrokerHandle,--export=BrokerContinue,--export-memory \
    -Wl,--initial-memory=131072,--max-memory=2097152 -o build/broker-guest.wasm
{
    printf '/* Generated by build-guest.sh from broker-guest.wasm. */\n#include "types.h"\n\n'
    xxd -i -n broker_guest_bytes build/broker-guest.wasm | \
        sed 's/^unsigned char/static const u8/; s/^unsigned int/static const usize/'
} > "$generated_stage/broker_guest_bytes.h"
mv "$generated_stage/broker_guest_bytes.h" src/generated/broker_guest_bytes.h
mv "$generated_stage/connection_guest_bytes.h" src/generated/connection_guest_bytes.h
mv "$generated_stage/business_guest_bytes.h" src/generated/business_guest_bytes.h
